package mdv

import (
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

// YAML 配置文件：exe 同目录下的 mdview.yml。
// Settings.useYaml 激活且文件存在时，它优先于 %AppData%\mdview\settings.json。
// 文件为生成格式：每个键上方带英文注释，保存时整体重写（保留注释模板）。

// YamlConfigPath 返回 mdview.yml 的完整路径（exe 同目录）。
func YamlConfigPath() string {
	exe, err := os.Executable()
	if err != nil {
		return ""
	}
	return filepath.Join(filepath.Dir(exe), "mdview.yml")
}

// yamlWriteLine 写一个带注释的标量键。
func yamlWriteLine(b *strings.Builder, comment, key, value string) {
	if comment != "" {
		for _, c := range strings.Split(comment, "\n") {
			b.WriteString("# " + c + "\n")
		}
	}
	b.WriteString(key + ": " + value + "\n")
}

// yamlQuote 把字符串按 YAML 单行标量输出；含特殊字符时加双引号。
func yamlQuote(s string) string {
	if s == "" {
		return `""`
	}
	if strings.ContainsAny(s, ":#\"'\n\t") || strings.HasPrefix(s, " ") || strings.HasSuffix(s, " ") {
		return strconv.Quote(s)
	}
	return s
}

// writeYamlSettings 整体重写 mdview.yml（注释模板 + 当前设置值）。
func writeYamlSettings(st Settings) error {
	path := YamlConfigPath()
	if path == "" {
		return os.ErrInvalid
	}
	var b strings.Builder
	b.WriteString("# mdview configuration file\n")
	b.WriteString("# Generated by mdview. When Settings > \"Use local YAML config\" is enabled,\n")
	b.WriteString("# this file takes priority over settings.json in %AppData%\\mdview.\n")
	b.WriteString("# Edit values below; comments are regenerated on save.\n\n")
	yamlWriteLine(&b, "UI theme: light | dark", "theme", yamlQuote(st.Theme))
	yamlWriteLine(&b, "Body font size in px (12-28)", "fontSize", strconv.Itoa(st.FontSize))
	yamlWriteLine(&b, "Wrap long lines inside code blocks", "codeWrap", strconv.FormatBool(st.CodeWrap))
	yamlWriteLine(&b, "Show line numbers in the source pane", "lineNo", strconv.FormatBool(st.LineNo))
	yamlWriteLine(&b, "Sidebar width in px (200-520)", "sidebarWidth", strconv.Itoa(st.SidebarWidth))
	yamlWriteLine(&b, "Remembered view mode: render | source | split | mindmap", "viewMode", yamlQuote(st.ViewMode))
	yamlWriteLine(&b, "UI language: zh-CN | en | ja | de", "language", yamlQuote(st.Language))
	yamlWriteLine(&b, "Always-on-top window", "pinned", strconv.FormatBool(st.Pinned))
	yamlWriteLine(&b, "Reload the file automatically when it changes outside mdview", "autoReload", strconv.FormatBool(st.AutoReload))
	yamlWriteLine(&b, "Block remote resources (http(s) images etc.) to stay 100% offline", "blockRemote", strconv.FormatBool(st.BlockRemote))
	yamlWriteLine(&b, "Remote whitelist: URL wildcard patterns (* and ? allowed), one per line.\n"+
		"# Matched URLs bypass the remote-resource block. Example:\n"+
		"#   https://cdn.example.com/*\n"+
		"#   *.example.org/*.png", "remoteAllow", "")
	for _, line := range strings.Split(st.RemoteAllow, "\n") {
		line = strings.TrimSpace(strings.TrimSuffix(line, "\r"))
		if line != "" {
			b.WriteString("  - " + yamlQuote(line) + "\n")
		}
	}
	yamlWriteLine(&b, "Mind map: max characters per line for node/notes (8-60)", "mmMaxLen", strconv.Itoa(st.MmMaxLen))
	yamlWriteLine(&b, "Use this YAML file as the settings source (keep true to stay in YAML mode)", "useYaml", strconv.FormatBool(st.UseYaml))
	yamlWriteLine(&b, "Last opened folder / file (window restore bookkeeping)", "lastFolder", yamlQuote(st.LastFolder))
	yamlWriteLine(&b, "", "lastFile", yamlQuote(st.LastFile))
	yamlWriteLine(&b, "Last window geometry; winW/winH below min size means \"not recorded\"", "winW", strconv.Itoa(st.WinW))
	yamlWriteLine(&b, "", "winH", strconv.Itoa(st.WinH))
	yamlWriteLine(&b, "Window position (may be negative on multi-monitor)", "winX", strconv.Itoa(st.WinX))
	yamlWriteLine(&b, "", "winY", strconv.Itoa(st.WinY))
	yamlWriteLine(&b, "Window was maximized on close", "winMax", strconv.FormatBool(st.WinMax))
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

// loadYamlSettings 解析 mdview.yml，把出现的键覆盖到 st 上。
// 极简 YAML 子集：`key: value` 标量 + `  - value` 列表项（仅 remoteAllow 用到），
// `#` 注释与空行忽略；不引入 YAML 依赖。
func loadYamlSettings(st *Settings) {
	path := YamlConfigPath()
	if path == "" {
		return
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return
	}
	var allow []string
	curKey := ""
	for _, raw := range strings.Split(string(data), "\n") {
		t := strings.TrimSpace(strings.TrimSuffix(raw, "\r"))
		if t == "" || strings.HasPrefix(t, "#") {
			continue
		}
		if strings.HasPrefix(t, "- ") && curKey == "remoteAllow" {
			allow = append(allow, yamlUnquote(strings.TrimSpace(t[2:])))
			continue
		}
		key, value, ok := strings.Cut(t, ":")
		if !ok {
			continue
		}
		key = strings.TrimSpace(key)
		value = strings.TrimSpace(value)
		curKey = key
		switch key {
		case "theme":
			if v := yamlUnquote(value); v == "light" || v == "dark" {
				st.Theme = v
			}
		case "fontSize":
			if n, e := strconv.Atoi(value); e == nil {
				st.FontSize = n
			}
		case "codeWrap":
			st.CodeWrap = value == "true"
		case "lineNo":
			st.LineNo = value == "true"
		case "sidebarWidth":
			if n, e := strconv.Atoi(value); e == nil {
				st.SidebarWidth = n
			}
		case "viewMode":
			st.ViewMode = yamlUnquote(value)
		case "language":
			st.Language = yamlUnquote(value)
		case "pinned":
			st.Pinned = value == "true"
		case "autoReload":
			st.AutoReload = value == "true"
		case "blockRemote":
			st.BlockRemote = value == "true"
		case "remoteAllow":
			// 列表项在上方分支收集；内联写法 `remoteAllow: a` 也支持（逗号分隔）
			if value != "" {
				allow = append(allow, strings.Split(value, ",")...)
			}
		case "mmMaxLen":
			if n, e := strconv.Atoi(value); e == nil {
				st.MmMaxLen = n
			}
		case "useYaml":
			st.UseYaml = value == "true"
		case "lastFolder":
			st.LastFolder = yamlUnquote(value)
		case "lastFile":
			st.LastFile = yamlUnquote(value)
		case "winW":
			if n, e := strconv.Atoi(value); e == nil {
				st.WinW = n
			}
		case "winH":
			if n, e := strconv.Atoi(value); e == nil {
				st.WinH = n
			}
		case "winX":
			if n, e := strconv.Atoi(value); e == nil {
				st.WinX = n
			}
		case "winY":
			if n, e := strconv.Atoi(value); e == nil {
				st.WinY = n
			}
		case "winMax":
			st.WinMax = value == "true"
		}
	}
	if len(allow) > 0 {
		st.RemoteAllow = strings.Join(allow, "\n")
	}
}

// yamlUnquote 去掉成对的双引号（生成端只可能写一层）。
func yamlUnquote(s string) string {
	if len(s) >= 2 && strings.HasPrefix(s, `"`) && strings.HasSuffix(s, `"`) {
		if u, err := strconv.Unquote(s); err == nil {
			return u
		}
	}
	return s
}

// yamlExists 判断 exe 同目录是否存在 mdview.yml。文件存在即视为 yml 配置源生效
// （并把 useYaml 视为开），不依赖存储的开关值。
func yamlExists() bool {
	fi, err := os.Stat(YamlConfigPath())
	return err == nil && !fi.IsDir()
}

// removeYaml 删除本地 mdview.yml（用户关掉 yml 开关时调用，避免再次打开时旧文件复活）。
func removeYaml() {
	_ = os.Remove(YamlConfigPath())
}
